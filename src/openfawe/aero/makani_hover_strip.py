"""Makani's hover strip model as a comparison module (decision 0020; off by default).

The model is a strip method: every panel (ten main-wing panels, four pylons, two
tails) samples the local apparent wind at 1 x 10 x 2 points, forms a dynamic-
pressure-weighted mean angle, iterates an elliptic induced angle alpha_i =
CL / (pi AR) with under-relaxation 0.4, blends the XFOIL table into the NACA 0012
full-circle table past the stall angles, applies Selig's 2D-to-3D post-stall
factor, the ``cl_weight``/``fudge_scale`` factors the source calls "a huge hack",
and an analytic tail downwash. It is kept here line for line so that the public
table ``database/m600/hover_model_sn02_wind_10_no_wake_model.json`` and OpenFAWE's
VSM + free-wake results can be compared with the same reference. Body axes are
Makani's (x forward, y right, z down); angles in radians.

Known difference between the source revision and the public table: the table was
generated by Makani commit 9cb0bb7 (its ``params`` block), and running the 1d66923
code on those parameters reproduces it only without ``_Convert2dTo3d`` (deep post-
stall agrees to 1e-4 then; differences of up to 0.06 in CZ and 0.19 in CY remain
in the -30..30 deg band). ``convert_2d_to_3d=False`` selects that behaviour.
"""
from dataclasses import dataclass, field
import json
import re
from pathlib import Path
import numpy as np

from .polars import MakaniAirfoil, load_makani_airfoil, post_stall_blend
from .vortex import _real

#: hover_model.py _CalcPanelForceMoment: induced-angle iteration constants.
MAX_ITERATIONS = 100
UNDER_RELAXATION = 0.4
ALPHA_EPSILON_RAD = np.deg2rad(0.05)
FUDGE_SCALE = 3.0
STALL_RANGE_WING_DEG = (25.0, 180.0)
STALL_RANGE_OTHER_DEG = (15.0, 180.0)
#: GetParams stall angles [deg] per airfoil file.
STALL_ANGLES_DEG = {"oref.json": (1.0, 16.0), "ref.json": (1.0, 16.0), "mp6d.json": (-10.0, 10.0),
                    "f8.json": (-10.0, 10.0), "approx_blade_rj8.json": (-10.0, 10.0)}


def apparent_wind_sph_to_cart(airspeed, alpha, beta):
    """apparent_wind_util.ApparentWindSphToCart."""
    x = -airspeed*np.cos(alpha)*np.cos(beta)
    y = -airspeed*np.sin(beta)
    z = -airspeed*np.sin(alpha)*np.cos(beta)
    return np.stack([x, y, z], axis=-1)


def apparent_wind_cart_to_sph(apparent_wind):
    """apparent_wind_util.ApparentWindCartToSph."""
    airspeed = np.linalg.norm(apparent_wind, axis=-1)
    alpha = np.arctan2(-apparent_wind[..., 2], -apparent_wind[..., 0])
    beta = np.arctan2(-apparent_wind[..., 1], np.sqrt(apparent_wind[..., 0]**2+apparent_wind[..., 2]**2))
    return airspeed, alpha, beta


@dataclass(frozen=True)
class StripPanel:
    """One hover-model panel (the ``panels``/``surfaces`` entries of the params block)."""
    name: str
    area: float
    span: float
    chord: float
    aspect_ratio: float
    cl_weight: float
    pos_b: np.ndarray
    incidence: float
    dcm_b2s: np.ndarray
    delta_index: int
    airfoil: MakaniAirfoil

    def __post_init__(self):
        object.__setattr__(self, "pos_b", np.asarray(self.pos_b, dtype=float).reshape(3))
        object.__setattr__(self, "dcm_b2s", np.asarray(self.dcm_b2s, dtype=float).reshape(3, 3))
        if not isinstance(self.airfoil, MakaniAirfoil):
            raise ValueError("StripPanel needs a MakaniAirfoil (blended)")

    @property
    def is_wing(self):
        return self.name[0:4] == "Wing"

    @property
    def is_pylon(self):
        return self.name[0:5] == "Pylon"


@dataclass(frozen=True)
class Rotor:
    pos: np.ndarray
    radius: float
    thrust: float

    def __post_init__(self):
        object.__setattr__(self, "pos", np.asarray(self.pos, dtype=float).reshape(3))


@dataclass(frozen=True)
class HoverStripModel:
    panels: tuple
    wing_area: float
    wing_b: float
    wing_c: float
    rho: float = 1.1
    use_wake_model: bool = False
    rotors: tuple = ()
    rotor_pitch: float = 0.0
    convert_2d_to_3d: bool = True
    source: dict = field(default_factory=dict)

    @classmethod
    def from_table_params(cls, table_path, airfoil_dir, *, use_wake_model=None, convert_2d_to_3d=True):
        """Build the model from the ``params`` block of a public hover table.

        Airfoils are re-blended with the stall angles the strings record. The
        table's ``rho`` is kept (coefficients do not depend on it).
        """
        table = json.loads(Path(table_path).read_text(encoding="utf-8"))
        params = table["params"]
        entries = params.get("panels", params.get("surfaces"))
        pattern = re.compile(r"^(?P<file>[\w.]+) with stall angles \((?P<low>[-\d.]+), (?P<high>[-\d.]+)\) \[deg\]\.$")
        high = load_makani_airfoil(Path(airfoil_dir)/"naca0012_high_aoa.json")
        cache, panels = {}, []
        for entry in entries:
            match = pattern.match(entry["airfoil"])
            if not match:
                raise ValueError("unexpected airfoil string "+entry["airfoil"])
            key = (match["file"], float(match["low"]), float(match["high"]))
            if key not in cache:
                cache[key] = post_stall_blend(load_makani_airfoil(Path(airfoil_dir)/key[0]), key[1:], high)
            panels.append(StripPanel(entry["name"], entry["area"], entry["span"], entry["chord"], entry["aspect_ratio"],
                                     entry["cl_weight"], entry["pos_b"], entry["incidence"], entry["dcm_b2s"],
                                     int(entry["delta_index"]), cache[key]))
        rotors = tuple(Rotor(r["pos"], r["radius"], r["thrust"]) for r in params.get("rotors", ()))
        return cls(tuple(panels), params["wing"]["area"], params["wing"]["b"], params["wing"]["c"], params["phys"]["rho"],
                   params["use_wake_model"] if use_wake_model is None else bool(use_wake_model), rotors,
                   params.get("rotor_pitch", 0.0), convert_2d_to_3d,
                   source=dict(table=str(table_path), generator_commit=params.get("git_commit"), wing_serial=params.get("wing_serial")))

    # ----------------------------------------------------------------- source routines
    def force_moment_coefficients(self, alphas, betas, deltas, omega_hat, apparent_wind_speed):
        """CalcForceMomentCoeffs: (..., 6) = [CX, CY, CZ, Cl, Cm, Cn] in Makani body axes."""
        alphas, betas = np.asarray(alphas, dtype=float), np.asarray(betas, dtype=float)
        deltas = np.asarray(deltas, dtype=float)
        if alphas.shape != betas.shape or deltas.shape[1:] != alphas.shape:
            raise ValueError("alphas, betas and deltas[1:] must share one shape")
        speed = float(_real(apparent_wind_speed, "apparent wind speed"))
        omega_hat = np.asarray(omega_hat, dtype=float).reshape(3)
        angular_rate_b = [omega_hat[0]*2.0*speed/self.wing_b, omega_hat[1]*2.0*speed/self.wing_c,
                          omega_hat[2]*2.0*speed/self.wing_b]
        force_b, moment_b = self._total_force_moment(alphas, betas, deltas, speed, angular_rate_b)
        normalization = 0.5*self.rho*speed**2.0*self.wing_area
        force_b = force_b/normalization
        moment_b = moment_b.copy()
        moment_b[..., 0] /= normalization*self.wing_b
        moment_b[..., 1] /= normalization*self.wing_c
        moment_b[..., 2] /= normalization*self.wing_b
        return np.concatenate((force_b, moment_b), axis=-1)

    def _total_force_moment(self, alphas, betas, deltas, speed, angular_rate_b):
        """_CalcTotalForceMoment."""
        total_force = np.zeros(alphas.shape+(3,))
        total_moment = np.zeros(alphas.shape+(3,))
        for panel in self.panels:
            panel_deltas = (deltas[panel.delta_index] if panel.delta_index >= 0 else
                            0.0 if panel.is_wing else None)
            airspeeds_s, alphas_s, betas_s = self._panel_local_apparent_wind_sph(alphas, betas, angular_rate_b, speed, panel)
            if panel.name == "Horizontal tail":
                downwash = estimate_downwash(panel.name, alphas)
            elif panel.name == "Vertical tail":
                downwash = estimate_downwash(panel.name, -betas)
            else:
                downwash = 0.0
            force_b, moment_b = self._panel_force_moment(airspeeds_s, alphas_s, betas_s, panel_deltas, panel, downwash)
            total_force += force_b
            total_moment += np.cross(panel.pos_b, force_b)+moment_b
        return total_force, total_moment

    def _panel_local_apparent_wind_sph(self, alphas, betas, angular_rate_b, speed, panel):
        """_CalcPanelLocalApparentWindSph: airspeed, alpha, beta in panel axes at every sample point."""
        use_wake = self.use_wake_model and not panel.is_wing and not panel.is_pylon
        points_b = panel_sampling_points(panel)                      # (n, 3)
        apparent_wind_b = apparent_wind_sph_to_cart(speed, alphas, betas)   # (..., 3)
        rotational = np.cross(np.asarray(angular_rate_b, dtype=float), points_b)  # (n, 3)
        local = apparent_wind_b[None, ...]-rotational.reshape((len(points_b),)+(1,)*alphas.ndim+(3,))
        if use_wake:
            shape = np.broadcast_shapes(local.shape, apparent_wind_b[None, ...].shape)
            local = local+sum_wake_velocity_increments(
                np.broadcast_to(points_b.reshape((len(points_b),)+(1,)*alphas.ndim+(3,)), shape),
                np.broadcast_to(apparent_wind_b[None, ...], shape), self)
        apparent_wind_s = local@panel.dcm_b2s.T
        return apparent_wind_cart_to_sph(apparent_wind_s)

    def _panel_force_moment(self, airspeeds_s, alphas_s, betas_s, deltas, panel, downwash_angles_s=0.0):
        """_CalcPanelForceMoment (sample axis first)."""
        mean_q = np.mean(0.5*self.rho*airspeeds_s**2.0*np.cos(betas_s)**2.0, axis=0)
        mean_alphas_s = np.mean(0.5*self.rho*airspeeds_s**2.0*np.cos(betas_s)**2.0*alphas_s, axis=0)/mean_q
        induced = np.zeros(np.shape(mean_alphas_s))
        iterations = 0
        converged = False
        while not converged:
            alphas_eff = mean_alphas_s-induced-downwash_angles_s+panel.incidence
            if panel.name == "Horizontal tail":
                cls, cds, cms = panel.airfoil.coefficients(alphas_eff+deltas)
            else:
                cls, cds, cms = panel.airfoil.coefficients(alphas_eff, 0.0 if deltas is None else deltas)
            if panel.is_wing:
                cl0s = panel.airfoil.coefficients(alphas_eff, 0.0)[0]
                weighted_cls = (cl0s+(cls-cl0s)*FUDGE_SCALE)*panel.cl_weight
                stall_range = STALL_RANGE_WING_DEG
            else:
                weighted_cls = cls*panel.cl_weight
                stall_range = STALL_RANGE_OTHER_DEG
            if self.convert_2d_to_3d:
                cls, cds, cms = convert_2d_to_3d(cls, cds, cms, mean_alphas_s-induced, panel.aspect_ratio, stall_range)
            alpha_ind = weighted_cls/(np.pi*panel.aspect_ratio)
            induced = UNDER_RELAXATION*alpha_ind+(1.0-UNDER_RELAXATION)*induced
            converged = np.allclose(induced, alpha_ind, atol=ALPHA_EPSILON_RAD)
            iterations += 1
            if iterations > MAX_ITERATIONS:
                break
        local = mean_alphas_s-induced
        cxs = -cds*np.cos(local)+cls*np.sin(local)
        czs = -cds*np.sin(local)-cls*np.cos(local)
        zeros = np.zeros(np.shape(cxs))
        force_s = (mean_q*panel.area)[..., None]*np.stack([cxs, zeros, czs], axis=-1)
        moment_s = (mean_q*panel.area*panel.chord)[..., None]*np.stack([zeros, cms, zeros], axis=-1)
        return force_s@panel.dcm_b2s, moment_s@panel.dcm_b2s


def panel_sampling_points(panel, thickness_ratio=0.2, num_points=(1, 10, 2)):
    """_GetPanelSamplingPoints: (prod(num_points), 3) body-frame points near the panel."""
    x_table = np.linspace(-panel.chord*0.75, panel.chord*0.25, num_points[0]) if num_points[0] > 1 else [0.0]
    y_table = np.linspace(-panel.span/2.0, panel.span/2.0, num_points[1]) if num_points[1] > 1 else [0.0]
    z_table = np.linspace(-panel.chord*thickness_ratio/2.0, panel.chord*thickness_ratio/2.0, num_points[2]) if num_points[2] > 1 else [0.0]
    xs, ys, zs = np.meshgrid(x_table, y_table, z_table, indexing="ij")
    points_s = np.reshape(np.array([xs.T, ys.T, zs.T]).T, (np.size(xs), 3))
    points_b = np.tensordot(panel.dcm_b2s.T, points_s.T, axes=1).T
    return points_b+np.tile(panel.pos_b, (np.size(xs), 1))


def estimate_downwash(panel_name, alphas):
    """_EstimateDownwash: analytic downwash at the horizontal/vertical stabiliser."""
    if panel_name == "Horizontal tail":
        aspect_ratio, panel_cl0, high_stall, low_stall, multiplier = 20.0, 2.05, 0.1, -0.3, 1.12
    elif panel_name == "Vertical tail":
        aspect_ratio, panel_cl0, high_stall, low_stall, multiplier = 2.4, -0.25, 0.2, -0.2, 1.06
    else:
        return 0.0
    dcl_dalpha = 2.0*np.pi*aspect_ratio/(2.0+aspect_ratio)
    unstalled = dcl_dalpha*alphas+panel_cl0
    stalled = 2.0*np.sin(alphas)*np.cos(alphas)
    weight = np.clip((high_stall-alphas)/0.05, -0.5, 0.5)+np.clip((alphas-low_stall)/0.05, -0.5, 0.5)
    panel_cl = weight*unstalled+(1.0-weight)*stalled
    return multiplier*2.0*panel_cl/(np.pi*aspect_ratio)


def convert_2d_to_3d(cls_2d, cds_2d, cms_2d, alphas_s, aspect_ratio, stall_range_deg):
    """_Convert2dTo3d: Selig (2010) post-stall factor k_cd applied to CL, CD, CM."""
    alpha_lower, alpha_upper = np.deg2rad(stall_range_deg[0]), np.deg2rad(stall_range_deg[1])
    w = np.cos(np.pi*(abs(alphas_s)-alpha_lower)/(alpha_upper-alpha_lower)-(np.pi/2.0))
    w = w*np.multiply((abs(alphas_s) >= alpha_lower).astype(int), (abs(alphas_s) <= alpha_upper).astype(int))
    k_cd = 1.0-0.41*(1.0-np.exp(-17.0/aspect_ratio))
    factor = 1.0-w*(1.0-k_cd)
    return cls_2d*factor, cds_2d*factor, cms_2d*factor


# ----------------------------------------------------------------------- wake_model.py
def sum_wake_velocity_increments(point_b, apparent_wind_b, model, num_steps=100, wake_length=15.0):
    """wake_model.SumWakeVelocityIncrementsAtPoint: Drela jet model of every rotor, summed in quadrature."""
    point_b = np.asarray(point_b, dtype=float)
    apparent_wind_b = np.broadcast_to(np.asarray(apparent_wind_b, dtype=float), point_b.shape)
    shape = point_b.shape[:-1]
    c, s = np.cos(model.rotor_pitch), np.sin(model.rotor_pitch)
    dcm_b2r = np.array([[c, 0.0, -s], [0.0, 1.0, 0.0], [s, 0.0, c]])
    apparent_wind_r = apparent_wind_b@dcm_b2r.T
    total = np.zeros(shape+(3,))
    for rotor in model.rotors:
        point_r = (point_b-rotor.pos)@dcm_b2r.T
        path_x, path_yz = _wake_path(rotor.thrust, apparent_wind_r, rotor.radius, model.rho, num_steps, wake_length)
        # Source quirk kept on purpose: the increment at the point is evaluated with the BODY-frame
        # apparent wind (apparent_wind_b), while the path uses the rotor-frame one.
        increment = _wake_velocity_increment_at_point(point_r, path_x, path_yz, rotor.thrust, apparent_wind_b,
                                                      rotor.radius, model.rho)
        total += np.sign(increment)*increment**2.0
    total = np.sign(total)*np.sqrt(abs(total))
    return total@dcm_b2r


def _wake_path(thrust, apparent_wind_r, rotor_radius, rho, num_steps, wake_length):
    """wake_model._CalcWakePath: Euler path of the wake core; returns x samples and (y, z) along it."""
    path = np.zeros(np.shape(apparent_wind_r)+(num_steps,))
    x_jet = np.linspace(0.0, wake_length, num_steps)
    dx = x_jet[1]-x_jet[0]
    for i in range(1, len(x_jet)):
        increment = _wake_velocity_increment((x_jet[i-1]+x_jet[i])/2.0, 0.0, thrust, apparent_wind_r, rotor_radius, rho)
        wake_vel_r = np.zeros(increment.shape+(3,))
        wake_vel_r[..., 0] = -increment
        total_vel_r = apparent_wind_r+wake_vel_r
        total_vel_x_r = total_vel_r[..., 0][..., None]
        path[..., -(i+1)] = path[..., -i]-dx*total_vel_r/total_vel_x_r
    return path[..., 0, :], path[..., 1:3, :]


def _wake_velocity_increment_at_point(point_r, path_x, path_yz, thrust, apparent_wind_r, rotor_radius, rho):
    """wake_model._CalcWakeVelocityIncrementAtPoint (interp1d linear with bounds error -> numpy.interp + check)."""
    point_x = point_r[..., 0]
    core_y = np.empty(point_x.shape)
    core_z = np.empty(point_x.shape)
    for index in np.ndindex(*point_x.shape):
        xs = path_x[index]
        if point_x[index] < xs.min() or point_x[index] > xs.max():
            raise ValueError("point outside the integrated wake path (interp1d bounds error in the source)")
        core_y[index] = np.interp(point_x[index], xs, path_yz[index][0])
        core_z[index] = np.interp(point_x[index], xs, path_yz[index][1])
    dist = np.sqrt((point_r[..., 1]-core_y)**2.0+(point_r[..., 2]-core_z)**2.0)
    increment = _wake_velocity_increment(-point_r[..., 0], dist, thrust, apparent_wind_r, rotor_radius, rho)
    return -np.dot(increment[..., None], np.array([[1.0, 0.0, 0.0]]))


def _wake_velocity_increment(x_jet, r_jet, thrust, apparent_wind_r, rotor_radius, rho):
    """wake_model._CalcWakeVelocityIncrement: Drela ASWING jet model (Eq. 120-134)."""
    assert np.all(np.asarray(x_jet) > 0.0)
    freestream = -np.asarray(apparent_wind_r)[..., 0]
    area = np.pi*rotor_radius**2.0
    increment = np.sqrt(freestream**2.0+2.0*thrust/(rho*area))-freestream
    contracted = rotor_radius*np.sqrt((freestream+increment/2.0)/(freestream+increment))
    shear = 0.11
    inner = shear*(abs(increment)/(freestream+1.0*increment))
    outer = shear*(abs(increment)/(freestream+0.5*increment))
    x_mix = contracted/inner
    b_jet = contracted+outer*x_jet
    c_jet = (contracted-inner*x_jet)*(x_jet < x_mix)
    k1 = c_jet**2.0+(9.0/10.0)*c_jet*(b_jet-c_jet)+(9.0/35.0)*(b_jet-c_jet)**2.0
    k2 = c_jet**2.0+(243.0/385.0)*c_jet*(b_jet-c_jet)+(243.0/1820.0)*(b_jet-c_jet)**2.0
    centre = np.sqrt((0.25*k1**2.0/k2**2.0*freestream**2.0)+(thrust/(rho*np.pi*k2)))-0.5*(k1/k2)*freestream
    return centre*(np.logical_and(b_jet > r_jet, r_jet >= c_jet)*(1.0-abs((r_jet-c_jet)/(b_jet-c_jet))**1.5)**2.0+(c_jet > r_jet))


def public_table_cfm(table_path):
    """(alphas_rad, betas_rad, cfm[alpha, beta, 6]) of a public hover table at zero flap and rate."""
    table = json.loads(Path(table_path).read_text(encoding="utf-8"))
    a, b = len(table["alphas"]), len(table["betas"])
    cfm = np.array(table["cfm"]).reshape(6, a, b).transpose(1, 2, 0)
    return np.array(table["alphas"]), np.array(table["betas"]), cfm
